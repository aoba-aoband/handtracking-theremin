"""Generate the shared SC validation contract from the new Effects registry."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gui.regular.effects import FX_SPECS


def generate():
    lines = ["// Generated by tools/generate_effect_specs.py", "(", "~regularFXSpecs = ("]
    for effect, specs in FX_SPECS.items():
        lines.append(f"    {effect}: (")
        lines.extend(f"        {key}: [{s.minimum}, {s.maximum}, {s.step}, {s.default}]" + ("," if i < len(specs)-1 else "") for i, (key, s) in enumerate(specs.items()))
        lines.append("    ),")
    lines[-1] = lines[-1].rstrip(",")
    lines.extend([");", ")", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    Path(__file__).resolve().parents[1].joinpath("sc/regular_effect_specs.scd").write_text(generate(), encoding="utf-8")
